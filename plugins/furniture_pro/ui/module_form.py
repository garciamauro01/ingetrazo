        self.sliding_track = self._spin(10, 200, 1, " mm", 5)
        form.addRow("Tipo de porta", self.door_combo)
        form.addRow("Quantidade", self.door_count)
        form.addRow("Folga entre portas", self.door_gap)
        form.addRow("Folga nas bordas", self.door_edge_gap)
        form.addRow("Folga vertical", self.door_vertical_gap)
