        outer = QVBoxLayout(page)
        box = QGroupBox("Caixa")
        form = QFormLayout(box)
        self.carcass_combo = QComboBox()
        for value, label in CARCASS_METHODS.items():
            self.carcass_combo.addItem(label, value)
        self.top_combo = QComboBox()
        for value, label in TOP_METHODS.items():
            self.top_combo.addItem(label, value)
        self.back_combo = QComboBox()
        for value, label in BACK_METHODS.items():
            self.back_combo.addItem(label, value)
        form.addRow("Método da caixa", self.carcass_combo)
        form.addRow("Topo", self.top_combo)
        form.addRow("Fundo", self.back_combo)
        self.back_recess = self._spin(0, 500)
        self.plinth_height = self._spin(0, 400)
        self.plinth_recess = self._spin(0, 500)
        form.addRow("Recuo do fundo", self.back_recess)
        form.addRow("Altura do rodapé", self.plinth_height)
        form.addRow("Recuo do rodapé", self.plinth_recess)
        self.shelf_spin = QSpinBox()
        self.shelf_spin.setRange(0, 30)
        self.divider_spin = QSpinBox()
        self.divider_spin.setRange(0, 12)
        self.shelf_spin.valueChanged.connect(self._schedule_preview)
        self.divider_spin.valueChanged.connect(self._schedule_preview)
        form.addRow("Prateleiras por baia", self.shelf_spin)
        form.addRow("Divisórias", self.divider_spin)
        outer.addWidget(box)

        fronts = QGroupBox("Frentes")
        form = QFormLayout(fronts)
        self.door_combo = QComboBox()
        for value, label in DOOR_TYPES.items():
            self.door_combo.addItem(label, value)
        self.door_combo.currentIndexChanged.connect(self._schedule_preview)
        self.door_count = QSpinBox()
        self.door_count.setRange(0, 8)
        self.door_count.valueChanged.connect(self._schedule_preview)
        self.door_gap = self._spin(0, 30, 1, " mm", 1)
        self.door_edge_gap = self._spin(0, 30, 1, " mm", 1)
        self.door_vertical_gap = self._spin(0, 30, 1, " mm", 1)
        self.door_overlap = self._spin(0, 80, 1, " mm", 5)
